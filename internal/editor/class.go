// class is vim's character class for word motions (mbyte.c utf_class): 0
// blank, 1 punctuation, 2 and up a kind of word character. Latin-1 goes
// by 'iskeyword' (@,48-57,_,192-255, where @ is the letters and µ); emoji
// are 3; the rest by nvim's table, word characters when not in it, so a
// run of Han is one word.
func class(r rune) int {
	switch {
	case r == ' ' || r == '\t' || r == 0 || r == 0xa0:
		return 0
	case r < 0x100:
		if r == '_' || r == 0xb5 || r >= 0xc0 || r < 0x80 && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			return 2
		}
		return 1
	}
	if _, ok := slices.BinarySearchFunc(emoji, r, func(e [2]rune, r rune) int { return cmpRange(e[0], e[1], r) }); ok {
		return 3
	}
	if i, ok := slices.BinarySearchFunc(classes, r, func(c classRange, r rune) int { return cmpRange(c.first, c.last, r) }); ok {
		return classes[i].cls
	}
	return 2
}

// cmpRange places r against the range first to last, for a binary search.
func cmpRange(first, last, r rune) int {
	switch {
	case last < r:
		return -1
	case first > r:
		return 1
	}
	return 0
}

type classRange struct {
	first, last rune
	cls         int
}

